def get_definition(text):
    if not text:
        return None
    synsets = wrdnet.synsets(text)
    if not synsets:
        return None
    definition = synsets[0].definition()
    example_sentences = synsets[0].examples()
    # print(definition, example_sentences)
    return definition, example_sentences

