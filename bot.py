#adding fuzzy matching technique.
#Fuzzy matching, or approximate string matching, 
# is a computer technique that finds text strings, words, 
# or data records that are similar rather than exact matches. 
# It assigns a similarity score to handle typos, spelling errors, 
# abbreviations, and formatting differences.
def fuzzy_match(text,choices,cutoff=0.7):
    match = difflib.get_close_matches(
        text, choices, n=1, cutoff = cutoff
    )
    if match:
        return match[0]
    return None

def contains_keyword(text,keywords):
    words = text.split()
